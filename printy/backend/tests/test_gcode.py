import base64
import struct
import zlib

from printy.gcode import is_sliced, is_source, parse_gcode_text
from printy.library import model_name_from


def _png(w: int, h: int) -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    raw = b"".join(b"\x00" + b"\xff\x80\x40" * w for _ in range(h))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def _thumb(w: int, h: int) -> str:
    data = base64.b64encode(_png(w, h)).decode()
    lines = [data[i:i + 78] for i in range(0, len(data), 78)]
    body = "\n".join(f"; {line}" for line in lines)
    return f"; thumbnail begin {w}x{h} {len(data)}\n{body}\n; thumbnail end\n"


ORCA = f"""; HEADER_BLOCK_START
; generated by OrcaSlicer 2.3.0
; estimated printing time (normal mode) = 2h 5m 30s
; HEADER_BLOCK_END
; THUMBNAIL_BLOCK_START
{_thumb(32, 32)}{_thumb(300, 300)}; THUMBNAIL_BLOCK_END
G28
G1 X10 Y10
; filament used [mm] = 12345.6
; filament used [g] = 37.25
; total filament used [g] = 37.25
; CONFIG_BLOCK_START
; filament_colour = #f5f5dc;#000000
; filament_type = PLA;PETG
; layer_height = 0.2
; nozzle_diameter = 0.4
; printer_model = Creality K2
; CONFIG_BLOCK_END
"""


def test_orca_metadata():
    m = parse_gcode_text(ORCA)
    assert m.duration_s == 2 * 3600 + 5 * 60 + 30
    assert m.filament_g == 37.25
    assert m.filament_m == 12.35
    assert m.color == "#F5F5DC"
    assert m.material == "PLA"
    assert m.layer_height == 0.2
    assert m.nozzle == 0.4
    assert m.printer_model == "Creality K2"
    assert m.thumbnail_png and m.thumbnail_png.startswith(b"\x89PNG")
    assert len(m.thumbnail_png) == len(_png(300, 300))  # the largest one


def test_cura_time():
    assert parse_gcode_text(";FLAVOR:Marlin\n;TIME:5400\n;Filament used: 3.2m\n").duration_s == 5400


def test_kinds():
    assert is_sliced("a.gcode") and is_sliced("a.gcode.3mf")
    assert not is_sliced("a.3mf") and is_source("a.3mf") and is_source("b.STL")
    assert not is_source("notes.txt")


def test_model_name():
    assert model_name_from("lampe_vague_abat-jour_K2_PLA_0.2mm_2h5m.gcode") == "Lampe vague abat-jour"
    assert model_name_from("Vague base_plate_1.gcode.3mf") == "Vague base"
    assert model_name_from("Vague base.stl") == "Vague base"
