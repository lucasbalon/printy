"""Fills a development instance with demo models, a demo printer and a week of jobs.

Usage (from printy/backend, server running on :8099):
    python scripts/seed_demo.py
"""

from __future__ import annotations

import base64
import json
import struct
import sys
import urllib.request
import uuid
import zlib
from datetime import datetime, timedelta

API = "http://127.0.0.1:8099/api/v1"


def png(width: int, height: int, pixel) -> bytes:  # noqa: ANN001
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for x in range(width):
            rows.extend(pixel(x, y))
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(bytes(rows), 9))
        + chunk(b"IEND", b"")
    )


def hex_rgb(h: str) -> tuple[int, int, int]:
    return int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)


def shade(rgb, f):  # noqa: ANN001
    return tuple(max(0, min(255, int(c * f))) for c in rgb)


def lamp_thumb(kind: str, color: str) -> bytes:
    """A flat silhouette of the object, lit from the left, on the slicer's grey."""
    bg = (236, 233, 228)
    rgb = hex_rgb(color)
    S = 220

    def pixel(x: int, y: int):  # noqa: ANN202
        u, v = x / S, y / S
        light = 1.08 - 0.35 * u
        if kind == "shade":  # truncated cone with ribs
            top, bot = 0.18, 0.82
            if top < v < bot:
                half = 0.16 + (v - top) / (bot - top) * 0.2
                if abs(u - 0.5) < half:
                    rib = 0.93 if int((u - 0.5 + half) / (2 * half) * 14) % 2 else 1.0
                    return shade(rgb, light * rib)
        elif kind == "base":
            if 0.62 < v < 0.8 and abs(u - 0.5) < 0.3:
                return shade(rgb, light)
            if 0.22 < v <= 0.62 and abs(u - 0.5) < 0.07:
                return shade(rgb, light * 0.95)
        elif kind == "mushroom":
            if 0.2 < v < 0.5 and ((u - 0.5) / 0.34) ** 2 + ((v - 0.5) / 0.3) ** 2 < 1:
                return shade(rgb, light)
            if 0.5 <= v < 0.82 and abs(u - 0.5) < 0.1 + (v - 0.5) * 0.25:
                return shade(rgb, light * 0.9)
        elif kind == "spiral":
            dx, dy = u - 0.5, v - 0.5
            r = (dx * dx + dy * dy) ** 0.5
            if r < 0.34 and int(r * 40) % 3:
                return shade(rgb, light * (0.9 + 0.2 * (dy + 0.5)))
        elif kind == "arch":
            dx, dy = u - 0.5, v - 0.72
            r = (dx * dx + dy * dy) ** 0.5
            if (0.2 < r < 0.32 and v < 0.72) or (0.72 <= v < 0.8 and 0.2 < abs(dx) < 0.32):
                return shade(rgb, light)
        return bg

    return png(S, S, pixel)


def gcode(name: str, kind: str, color: str, material: str, minutes: int, grams: float, printer: str) -> bytes:
    thumb = base64.b64encode(lamp_thumb(kind, color)).decode()
    lines = [thumb[i : i + 78] for i in range(0, len(thumb), 78)]
    block = "\n".join(f"; {line}" for line in lines)
    h, m = divmod(minutes, 60)
    return f"""; generated by OrcaSlicer 2.3.0
; estimated printing time (normal mode) = {h}h {m}m 0s
; THUMBNAIL_BLOCK_START
; thumbnail begin 220x220 {len(thumb)}
{block}
; thumbnail end
; THUMBNAIL_BLOCK_END
G28
; filament used [mm] = {grams * 330:.1f}
; filament used [g] = {grams}
; filament_colour = {color}
; filament_type = {material}
; layer_height = 0.2
; nozzle_diameter = 0.4
; printer_model = {printer}
""".encode()


def call(method: str, path: str, body=None, files=None):  # noqa: ANN001
    headers = {}
    data = None
    if files:
        boundary = uuid.uuid4().hex
        parts = []
        for filename, content in files:
            parts.append(
                f'--{boundary}\r\nContent-Disposition: form-data; name="files"; filename="{filename}"\r\n'
                "Content-Type: application/octet-stream\r\n\r\n".encode() + content + b"\r\n"
            )
        data = b"".join(parts) + f"--{boundary}--\r\n".encode()
        headers["Content-Type"] = f"multipart/form-data; boundary={boundary}"
    elif body is not None:
        data = json.dumps(body).encode()
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(API + path, data=data, method=method, headers=headers)
    with urllib.request.urlopen(req) as r:
        raw = r.read()
        return json.loads(raw) if raw else None


MODELS = [
    ("vague_abat-jour_K2_PLA.gcode", "shade", "#F4F1EA", "PLA", 312, 148.6, ["vague", "abat-jour"]),
    ("vague_abat-jour_noir_K2_PLA.gcode", "shade", "#26221F", "PLA", 312, 148.6, None),
    ("vague_base_K2_PLA.gcode", "base", "#26221F", "PLA", 96, 61.2, ["vague", "base"]),
    ("champignon_K2_PETG.gcode", "mushroom", "#E7D6B8", "PETG", 425, 210.4, ["champignon"]),
    ("diffuseur_spirale_K2_PLA.gcode", "spiral", "#FAFAF7", "PLA", 188, 74.0, ["diffuseur"]),
    ("applique_arche_K2_PLA.gcode", "arch", "#B4603E", "PLA", 255, 132.9, ["applique"]),
]


def main() -> None:
    if call("GET", "/printers"):
        sys.exit("Already seeded (printers exist).")
    printer = call(
        "POST",
        "/printers",
        {
            "name": "K2",
            "driver": "demo",
            "options": {"speed": 60},
            "switch_entity": "switch.prise_k2",
            "power_entity": "sensor.prise_k2_puissance",
            "camera_source": "none",
        },
    )
    sliced = {}
    for filename, kind, color, mat, minutes, grams, tags in MODELS:
        res = call("POST", "/upload", files=[(filename, gcode(filename, kind, color, mat, minutes, grams, "Creality K2"))])
        model_id = res["imported"][0]["model_id"]
        if tags:
            call("PATCH", f"/models/{model_id}", {"tags": tags})
        model = call("GET", f"/models/{model_id}")
        sliced[filename] = model["sliced"][-1]["id"]

    today = datetime.now().astimezone().replace(minute=0, second=0, microsecond=0)
    plan = [
        ("vague_base_K2_PLA.gcode", today.replace(hour=22)),
        ("champignon_K2_PETG.gcode", (today + timedelta(days=1)).replace(hour=8)),
        ("vague_abat-jour_K2_PLA.gcode", (today + timedelta(days=1)).replace(hour=22)),
        ("diffuseur_spirale_K2_PLA.gcode", (today + timedelta(days=2)).replace(hour=14)),
        ("applique_arche_K2_PLA.gcode", (today + timedelta(days=3)).replace(hour=23)),
    ]
    for filename, start in plan:
        if start > datetime.now().astimezone():
            call("POST", "/jobs", {"sliced_file_id": sliced[filename], "printer_id": printer["id"], "start_at": start.isoformat()})
    print("Seeded.")


if __name__ == "__main__":
    main()
